/**
 * Registry Helper Functions
 */

export function getSupportedFormats(): FileFormat[] {
  return SUPPORTED_FILE_FORMATS;
}

export function getFormatById(id: string): FileFormat | undefined {
  const norm = id.toLowerCase().trim();
  return SUPPORTED_FILE_FORMATS.find((f) => f.id === norm || f.extension === norm);
}

export function getAllConversionDefinitions(): ConversionDefinition[] {
  return UNIVERSAL_CONVERSION_REGISTRY;
}

export function getAvailableOutputsForFormat(inputFormatId: string): FileFormat[] {
  const norm = inputFormatId.toLowerCase().trim();
  const defs = UNIVERSAL_CONVERSION_REGISTRY.filter(
    (c) => c.status === 'supported' && (c.inputFormat === norm || c.inputExtension === norm)
  );

  const outputFormatIds = new Set(defs.map((d) => d.outputFormat));
  return SUPPORTED_FILE_FORMATS.filter((f) => outputFormatIds.has(f.id));
}

export function findConversionDefinition(
  inputFormatId: string,
  outputFormatId: string
): ConversionDefinition | undefined {
  const normIn = inputFormatId.toLowerCase().trim();
  const normOut = outputFormatId.toLowerCase().trim();

  return UNIVERSAL_CONVERSION_REGISTRY.find(
    (c) =>
      c.status === 'supported' &&
      (c.inputFormat === normIn || c.inputExtension === normIn) &&
      (c.outputFormat === normOut || c.outputExtension === normOut)
  );
}
